"""Writes crop_tables.h: Catmull-Rom weights (x4096) for each phase of each
crop. A crop of ratio a/b maps output pixel x to source 2a*x + (b-a)(n-1)
in units of 1/(2b) pixel, so the phase repeats every 2b outputs."""
CROPS = [(4, 5, "35mm"), (7, 10, "40mm"), (14, 25, "50mm")]  # 28/35, 28/40, 28/50

def weights(t):
    w = [(-t**3 + 2*t**2 - t) / 2, (3*t**3 - 5*t**2 + 2) / 2,
         (-3*t**3 + 4*t**2 + t) / 2, (t**3 - t**2) / 2]
    q = [round(v * 4096) for v in w]
    q[1] += 4096 - sum(q)          # exact unit sum, so flat areas stay flat
    return q

rows, offsets, off = [], [], 0
for a, b, name in CROPS:
    offsets.append(off)
    for ph in range(2 * b):
        rows.append((weights(ph / (2 * b)), f"{name} phase {ph}"))
    off += 2 * b

with open("crop_tables.h", "w", newline="\n") as f:
    f.write("/* Generated by gen_tables.py. Do not edit. */\n")
    f.write("#ifndef CROP_TABLES_H\n#define CROP_TABLES_H\n")
    f.write("/* Index 0 is Off. */\n")
    f.write("static const u8 CROP_A[4] = {0, %s};\n" % ", ".join(str(a) for a, _, _ in CROPS))
    f.write("static const u8 CROP_B[4] = {0, %s};\n" % ", ".join(str(b) for _, b, _ in CROPS))
    f.write("static const u8 CROP_PHASE0[4] = {0, %s};\n" % ", ".join(map(str, offsets)))
    f.write("static const short CROP_W[%d][4] = {\n" % len(rows))
    for q, c in rows:
        f.write("    {%d, %d, %d, %d}, /* %s */\n" % (*q, c))
    f.write("};\n#endif\n")
print(len(rows), "phases")
